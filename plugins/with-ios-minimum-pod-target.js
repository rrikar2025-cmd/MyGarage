const { withPodfile } = require('@expo/config-plugins');

const MINIMUM_IOS_VERSION = '15.1';
const GENERATED_BLOCK_START = '# @generated by with-ios-minimum-pod-target';
const GENERATED_BLOCK_END = '# @end generated minimum iOS pod target';

const GENERATED_BLOCK = `${GENERATED_BLOCK_START}
    installer.pods_project.targets.each do |target|
      target.build_configurations.each do |build_configuration|
        deployment_target = build_configuration.build_settings['IPHONEOS_DEPLOYMENT_TARGET']
        if deployment_target.nil? || Gem::Version.new(deployment_target) < Gem::Version.new('${MINIMUM_IOS_VERSION}')
          build_configuration.build_settings['IPHONEOS_DEPLOYMENT_TARGET'] = '${MINIMUM_IOS_VERSION}'
        end
      end
    end
    ${GENERATED_BLOCK_END}`;

const withIosMinimumPodTarget = (config) =>
  withPodfile(config, (podfileConfig) => {
    let { contents } = podfileConfig.modResults;

    const generatedBlockPattern = new RegExp(
      `^[\\t ]*${GENERATED_BLOCK_START}[\\s\\S]*?^[\\t ]*${GENERATED_BLOCK_END}\\n?`,
      'm',
    );
    contents = contents.replace(generatedBlockPattern, '');

    const postInstallEndPattern = /(^  post_install do \|installer\|[\s\S]*?)(^  end\nend\s*$)/m;
    if (!postInstallEndPattern.test(contents)) {
      throw new Error('Could not find the CocoaPods post_install block in ios/Podfile.');
    }

    podfileConfig.modResults.contents = contents.replace(
      postInstallEndPattern,
      (_match, postInstallBody, postInstallEnd) =>
        `${postInstallBody}${GENERATED_BLOCK}\n${postInstallEnd}`,
    );

    return podfileConfig;
  });

module.exports = withIosMinimumPodTarget;
