const { withAppBuildGradle } = require('@expo/config-plugins');

const VARIABLES_START = '// @generated by with-versioned-android-release:variables';
const VARIABLES_END = '// @end generated variables';
const OUTPUT_START = '// @generated by with-versioned-android-release:output';
const OUTPUT_END = '// @end generated output';

const removeGeneratedBlock = (contents, start, end) =>
  contents.replace(new RegExp(`${start}[\\s\\S]*?${end}\\n?`, 'g'), '');

const assertVersion = (versionName, versionCode) => {
  if (!/^[0-9A-Za-z.+-]+$/.test(versionName)) {
    throw new Error(`Unsupported Android version name: ${versionName}`);
  }

  if (!Number.isInteger(versionCode) || versionCode < 1) {
    throw new Error(`Android version code must be a positive integer: ${versionCode}`);
  }
};

const withVersionedAndroidRelease = (config) =>
  withAppBuildGradle(config, (gradleConfig) => {
    if (gradleConfig.modResults.language !== 'groovy') {
      throw new Error('MyGarage Android release configuration requires Groovy Gradle.');
    }

    const versionName = config.version ?? '1.0.0';
    const versionCode = config.android?.versionCode ?? 1;
    assertVersion(versionName, versionCode);

    let contents = gradleConfig.modResults.contents;
    contents = removeGeneratedBlock(contents, VARIABLES_START, VARIABLES_END);
    contents = removeGeneratedBlock(contents, OUTPUT_START, OUTPUT_END);

    const variables = `${VARIABLES_START}
def myGarageVersionCode = (findProperty("myGarageVersionCode") ?: ${versionCode}).toInteger()
def myGarageVersionName = (findProperty("myGarageVersionName") ?: "${versionName}").toString()
${VARIABLES_END}

`;

    if (!contents.includes('def projectRoot =')) {
      throw new Error('Could not find projectRoot in android/app/build.gradle.');
    }

    contents = contents.replace('def projectRoot =', `${variables}def projectRoot =`);
    contents = contents.replace(
      /^\s*versionCode\s+.+$/m,
      '        versionCode myGarageVersionCode',
    );
    contents = contents.replace(
      /^\s*versionName\s+.+$/m,
      '        versionName myGarageVersionName',
    );

    const outputConfiguration = `${OUTPUT_START}
    applicationVariants.configureEach { variant ->
        if (variant.buildType.name == "release") {
            variant.outputs.configureEach {
                outputFileName = "MyGarage-${'$'}{variant.versionName}(${'$'}{variant.versionCode})-${'$'}{variant.buildType.name}.apk"
            }
        }
    }
    ${OUTPUT_END}

`;

    if (!contents.includes('android {')) {
      throw new Error('Could not find the android block in android/app/build.gradle.');
    }

    gradleConfig.modResults.contents = contents.replace(
      'android {',
      `android {\n    ${outputConfiguration}`,
    );
    return gradleConfig;
  });

module.exports = withVersionedAndroidRelease;
